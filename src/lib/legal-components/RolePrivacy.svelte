<h1>Privacy Policy</h1>
<p><strong>Last Updated:</strong> July 17, 2026</p>
<h2>Introduction</h2>
<p>Voicely Role (&quot;the Bot&quot;) is a Discord bot developed by Gozar Productions LLC. This Privacy Policy explains what information the Bot stores, how it is used, and your rights regarding that information.</p>
<p>By using Voicely Role, you agree to the practices described in this Privacy Policy.</p>
<h2>Information We Store</h2>
<p>Voicely Role stores only the information necessary to provide its functionality.</p>
<p>This may include:</p>
<ul>
<li>Discord server IDs</li>
<li>Discord channel IDs</li>
<li>Discord role IDs</li>
<li>Discord user IDs for excluded users</li>
<li>Configured administrator role IDs</li>
<li>Voice notification configurations</li>
<li>Custom notification messages</li>
<li>Internal notification state required for the Bot to determine when notifications should be sent</li>
</ul>
<p>Voicely Role does <strong>not</strong> store:</p>
<ul>
<li>Voice communications</li>
<li>Message contents</li>
<li>Usernames</li>
<li>Display names</li>
<li>Voice recordings</li>
<li>Personal profile information</li>
<li>Email addresses</li>
<li>IP addresses</li>
</ul>
<h2>How Information Is Used</h2>
<p>Stored information is used solely to:</p>
<ul>
<li>Monitor configured voice channels</li>
<li>Determine when notification thresholds have been reached</li>
<li>Send configured role notifications</li>
<li>Manage server-specific settings</li>
<li>Prevent duplicate notifications until channels have reset</li>
</ul>
<h2>Data Sharing</h2>
<p>Voicely Role does not sell, rent, or share stored data with third parties except when required by law.</p>
<h2>Data Retention</h2>
<p>Configuration data is retained until:</p>
<ul>
<li>It is removed by an authorized server administrator,</li>
<li>The Bot is removed from the server, or</li>
<li>The data is otherwise deleted during maintenance.</li>
</ul>
<h2>Security</h2>
<p>Reasonable measures are taken to protect stored configuration data. However, no system can guarantee absolute security.</p>
<h2>Third-Party Services</h2>
<p>Voicely Role operates through Discord and is subject to Discord&#39;s own Privacy Policy and Terms of Service.</p>
<h2>Your Rights</h2>
<p>Server administrators may modify or remove stored server configuration at any time using the Bot&#39;s commands.</p>
<p>To request deletion of any remaining stored data, please contact Gozar Productions LLC.</p>
